import type { Currency, JobPriority, RecurrenceUnit, Role } from "@fieldops/shared";
import type { Page } from "./types";

// Maintenance plans that generate recurring jobs (JOB-13) and the owner's daily digest (NOT-04).

export interface RecurrenceRecord {
  id: string;
  customerId: string;
  siteId: string;
  equipmentId: string | null;
  serviceTypeId: string | null;
  title: string;
  description: string | null;
  priority: JobPriority;
  intervalUnit: RecurrenceUnit;
  intervalCount: number;
  startsOn: string;
  endsOn: string | null;
  /** Preferred visit start ("HH:MM", organization time zone) and length; both or neither. */
  windowStart: string | null;
  windowMinutes: number | null;
  /** Jobs are created this many days before their date. */
  leadDays: number;
  /** The first occurrence that has no job yet. Past `endsOn` once the plan has ended. */
  nextOn: string;
  /** Preferred technician, suggested on generated jobs. */
  leadMemberId: string | null;
  /** False while the office has paused the plan. */
  active: boolean;
  createdBy: string | null;
  createdAt: Date;
  updatedAt: Date;
}

/** A plan with the names the lists show and what it has generated so far. */
export interface RecurrenceView extends RecurrenceRecord {
  customer: { id: string; name: string };
  site: { id: string; label: string; city: string };
  serviceType: { id: string; name: string } | null;
  leadMember: { memberId: string; name: string } | null;
  /** Jobs generated by the plan (deleted jobs excluded). */
  jobCount: number;
  /** The latest occurrence date that has a job, deleted jobs included; null before the first. */
  lastOccurrence: string | null;
}

export type NewRecurrence = Omit<RecurrenceRecord, "id" | "createdAt" | "updatedAt">;
export type RecurrencePatch = Partial<
  Omit<RecurrenceRecord, "id" | "customerId" | "createdBy" | "createdAt">
>;

export interface RecurrenceListFilters {
  customerId?: string;
  active?: boolean;
  limit: number;
  cursor?: string;
}

export interface RecurrenceRepo {
  /** Plans by next date (then id), keyset paginated. Deleted plans are never listed. */
  list(filters: RecurrenceListFilters): Promise<Page<RecurrenceView>>;
  get(id: string): Promise<RecurrenceView | null>;
  create(data: NewRecurrence): Promise<RecurrenceRecord>;
  update(id: string, patch: RecurrencePatch): Promise<RecurrenceRecord | null>;
  /** Soft delete: the plan stops and disappears; the jobs it generated stay. */
  softDelete(id: string): Promise<boolean>;
  /**
   * Active plans whose next occurrence is within their lead days of `today` and not past their end, and whose
   * customer and site still exist. Locks each plan for this transaction and skips plans another transaction is
   * generating.
   */
  due(today: string): Promise<RecurrenceRecord[]>;
  /** Moves a plan's next date after generating its jobs. Not an edit: `updatedAt` stays. */
  advance(id: string, nextOn: string): Promise<void>;
  /** The occurrence dates of a plan that already have a job (deleted jobs included), from `from` on. */
  occurrencesWithJobs(id: string, from: string): Promise<string[]>;
}

// ---------------------------------------------------------------- daily digest (NOT-04)

export interface DigestRecipient {
  userId: string;
  name: string;
  email: string;
  role: Role;
}

export interface DigestOverdueJob {
  id: string;
  number: number;
  title: string;
  customerName: string;
  /** The deadline the job missed. */
  dueAt: Date | null;
}

/** One local day of the organization, for the digest. Rates are null when nothing was measured. */
export interface DigestSummary {
  /** The local date summarized ("yesterday"). */
  date: string;
  jobsCreated: number;
  jobsCompleted: number;
  /** Resolution SLA met ÷ (met + breached) for jobs completed that day. */
  slaMet: number;
  slaMeasured: number;
  /** Completed jobs that needed no other visit. */
  firstVisit: number;
  currency: Currency;
  /** Invoices issued that day (not drafts or voided) and payments received that day. */
  invoicedMinor: number;
  collectedMinor: number;
  /** Open jobs whose current SLA is breached, as of now: the total and the most overdue ones. */
  overdueCount: number;
  overdue: DigestOverdueJob[];
  /** Part and expense requests waiting for a decision. */
  pendingApprovals: number;
}

export interface DigestRepo {
  /**
   * Members who should get the digest for `date` and haven't yet: owners unless they turned it off, admins
   * who turned it on.
   */
  recipients(date: string): Promise<DigestRecipient[]>;
  /** The figures for one local date, computed in SQL, with up to `overdueLimit` overdue jobs. */
  summary(date: string, overdueLimit: number): Promise<DigestSummary>;
  /** Records the digest of a user and date. False when it was already recorded (sent by another run). */
  record(userId: string, date: string, sentAt: Date): Promise<boolean>;
}

/** Writes the digest email to the outbox in the caller's transaction. Implemented by the worker. */
export interface DigestMailer {
  send(input: { recipient: DigestRecipient; summary: DigestSummary; date: string }): Promise<void>;
}
