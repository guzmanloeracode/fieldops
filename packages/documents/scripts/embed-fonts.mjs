// Regenerates src/fonts.generated.ts from the TTF files in fonts/.
//
// The fonts are Inter 4.001 (SIL Open Font License 1.1, fonts/OFL.txt), regular and bold, subset to Latin with
// fontTools so the module stays small:
//   pyftsubset Inter-<Weight>.ttf --unicodes="U+0020-007E,U+00A0-024F,U+02C6-02DD,U+2000-206F,U+20A0-20CF,
//     U+2100-214F,U+2190-2199,U+2212,U+2264-2265,U+2713,U+2715,U+25CF,U+FFFD"
//     --layout-features='kern,liga,calt,ccmp,locl,mark,mkmk' --name-IDs='*' --name-languages='*'
//
// They are embedded as data URLs because the web app bundles this package: a file read relative to the source
// would point inside the build output, and a data URL needs no file at run time.
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../", import.meta.url);
const font = (name) => readFileSync(new URL(`fonts/${name}`, dir)).toString("base64");

const out = `// Generated by scripts/embed-fonts.mjs from fonts/*.ttf (Inter, SIL Open Font License 1.1). Don't edit.

export const INTER_REGULAR =
  "data:font/ttf;base64,${font("Inter-Regular.ttf")}";

export const INTER_BOLD =
  "data:font/ttf;base64,${font("Inter-Bold.ttf")}";
`;
writeFileSync(new URL("src/fonts.generated.ts", dir), out);
